/**
 * @param decimals จำนวนทศนิยมที่เครื่องมือวัดจริงให้ได้ (อุณหภูมิ/น้ำหนัก = 1, ที่เหลือ = 0)
 *
 * ใช้ Number() ครอบอีกชั้นเพื่อตัดศูนย์ท้ายทิ้ง
 * toFixed(1) ของ 36 จะได้ "36.0" ซึ่งอ่านแปลกกว่า "36"
 */
export function fmtVital(value: number | undefined | null, decimals = 0): string {
  if (value === undefined || value === null || Number.isNaN(value)) return '';
  return String(Number(value.toFixed(decimals)));
}
