/**
 * ==============================================================================
 * จัดรูปแบบเลขบัตรประชาชนไทย [role แพทย์]
 * ==============================================================================
 * เลขบัตรประชาชนไทยมี 13 หลัก รูปแบบมาตรฐานคือ 1-2345-67890-12-3
 * แบ่งเป็น 1-4-5-2-1 หลัก
 *
 * ทำไมต้องแบ่ง: เลข 13 หลักติดกัน (1634586583903) อ่านทวนทีละตัวยากมาก
 * แพทย์ต้องตรวจสอบเลขบัตรกับบัตรจริงของผู้ป่วยก่อนออกใบรับรอง/ใบสั่งยา
 * ถ้าอ่านผิดตัวเดียวก็ออกเอกสารผิดคน การแบ่งกลุ่มช่วยลดความผิดพลาดตรงนี้
 *
 * หมายเหตุ: ฟังก์ชันนี้ใช้ "แสดงผล" เท่านั้น
 * เวลาคัดลอกหรือส่งกลับ backend ให้ใช้ค่าดิบเสมอ เพราะฐานข้อมูลเก็บเป็นตัวเลขล้วน
 * และระบบอื่นที่เอาไปวางต่อ (เช่น ระบบเบิกจ่าย) รับเฉพาะตัวเลขล้วน
 */

/** ตัดทุกอย่างที่ไม่ใช่ตัวเลขออก ใช้ตอนคัดลอกหรือส่งกลับ backend */
export function rawNationalId(value: string | undefined | null): string {
  if (!value) return '';
  return value.replace(/\D/g, '');
}

/**
 * แปลงเลขบัตรเป็นรูปแบบ 1-2345-67890-12-3
 *
 * ค่าที่ไม่ใช่ 13 หลัก (เช่น พาสปอร์ตชาวต่างชาติ หรือข้อมูลเก่าที่กรอกไม่ครบ)
 * จะคืนค่าเดิมกลับไปทั้งดุ้น ไม่พยายามดัดให้เข้ารูปแบบ
 * เพราะการตัดแบ่งมั่วๆ จะทำให้เลขที่ผิดอยู่แล้วดูเหมือนเลขที่ถูกต้อง
 */
export function formatNationalId(value: string | undefined | null): string {
  if (!value) return '';

  const digits = rawNationalId(value);
  if (digits.length !== 13) return value;

  return [
    digits.slice(0, 1),
    digits.slice(1, 5),
    digits.slice(5, 10),
    digits.slice(10, 12),
    digits.slice(12, 13),
  ].join('-');
}
