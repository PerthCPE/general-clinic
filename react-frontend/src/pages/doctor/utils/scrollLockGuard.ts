import { useEffect } from 'react';

/**
 * ==============================================================================
 * ปลดล็อกการเลื่อนหน้าจอที่ค้างมาจากโมดูลอื่น [role แพทย์]
 * ==============================================================================
 * อาการ: เข้าหน้าของแพทย์แล้วเลื่อนเมาส์ไม่ลง ทั้งที่เนื้อหายาวเกินจอ
 *        และไม่มีแถบเลื่อนขึ้นมาให้ลากด้วย
 *
 * ต้นเหตุ (ไม่ได้อยู่ในโค้ดของแพทย์):
 *   components/Common/ClinicModalPortal.tsx ตอนเปิดกล่องจะสั่ง
 *       document.body.style.overflow = 'hidden'
 *       document.documentElement.style.overflow = 'hidden'
 *   แล้วตอนปิดจะคืนค่า "ที่จำไว้ตอนเปิด" กลับไป
 *
 *   ปัญหาคือถ้ามีกล่องซ้อนกัน 2 ชั้น (หรือกล่องใหม่เปิดก่อนกล่องเก่าจะถูกถอด)
 *   กล่องชั้นในจะจำค่าตอนเปิดได้เป็น 'hidden' (เพราะกล่องชั้นนอกล็อกไว้แล้ว)
 *   พอปิดครบทุกชั้น ค่าที่ถูกคืนกลับมาจึงเป็น 'hidden' ค้างอยู่ถาวร
 *
 * ทำไมมันตามมาถึงหน้าแพทย์ได้:
 *   ทั้งระบบเป็น SPA หน้าเดียว การเปลี่ยนเมนูคือการเปลี่ยน state ใน App.tsx
 *   ไม่ได้โหลดหน้าใหม่ ดังนั้น style ที่ค้างบน <html>/<body> จึงอยู่ยาว
 *   จนกว่าจะกด refresh
 *
 * ตัวนี้ทำอะไร:
 *   ตอนหน้าของแพทย์ถูกเปิด ให้ล้าง overflow ที่ค้างอยู่ทิ้ง
 *   ทำได้อย่างปลอดภัยเพราะหน้าฝั่งแพทย์ไม่ได้ใช้ ClinicModalPortal เลย
 *   (กล่องยืนยันของแพทย์เป็น fixed inset-0 ธรรมดา ไม่ล็อก scroll ของ body)
 *   จึงไม่มีกรณีที่ "ล็อกอยู่อย่างถูกต้อง" ให้เผลอไปปลด
 *
 * หมายเหตุ: นี่เป็นการกันอาการที่ปลายทาง ไม่ใช่การแก้ต้นเหตุ
 * ต้นเหตุจริงอยู่ที่ ClinicModalPortal ซึ่งเป็นไฟล์กลางของเพื่อน
 * วิธีแก้ที่ถูกคือให้มันนับจำนวนกล่องที่เปิดอยู่ (ref count)
 * แล้วล้าง overflow ทิ้งเมื่อกล่องสุดท้ายปิด แทนการคืนค่าที่จำไว้
 */
export function useUnlockPageScroll(): void {
  useEffect(() => {
    const bodyLocked = document.body.style.overflow === 'hidden';
    const htmlLocked = document.documentElement.style.overflow === 'hidden';

    if (!bodyLocked && !htmlLocked) return;

    // ล้างเฉพาะ inline style ที่ถูกเขียนทับไว้ ไม่ได้ไปยุ่งกับ CSS ในไฟล์
    document.body.style.overflow = '';
    document.documentElement.style.overflow = '';

    // paddingRight ถูกใส่คู่กันมาเพื่อชดเชยความกว้างแถบเลื่อน
    // ถ้าไม่ล้างด้วย จะเหลือขอบขาวด้านขวาค้างไว้
    document.body.style.paddingRight = '';

    console.warn(
      '[doctor] พบ overflow:hidden ค้างอยู่บน <html>/<body> จึงล้างทิ้งให้ ' +
        '— ค่านี้ถูกตั้งโดย components/Common/ClinicModalPortal.tsx ' +
        'ตอนเปิดกล่องจากหน้าอื่น แล้วคืนค่าไม่ครบตอนปิด'
    );
  }, []);
}
